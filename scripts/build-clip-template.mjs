// Regenerates src/ableton/clipTemplate.ts from templates/Labyrinth.alc.
//
// A .alc is gzipped Live XML. We keep the *uncompressed* XML in the bundle so
// export only ever has to compress, never decompress, and store it as a
// generated module rather than fetching the file at runtime — an artifact that
// has to be downloaded before you can save is a worse failure mode than 60kB.
//
// Run: npm run build:clip-template

import { gunzipSync } from 'node:zlib'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'templates', 'Labyrinth.alc')
const target = join(root, 'src', 'ableton', 'clipTemplate.ts')

const xml = gunzipSync(readFileSync(source)).toString('utf8')

// Fail loudly rather than emitting a template the exporter cannot anchor into.
const required = ['<KeyTracks />', '<GrooveId Value="0" />', '<NoteIdGenerator>']
for (const anchor of required) {
  const count = xml.split(anchor).length - 1
  if (count !== 1 && anchor !== '<NoteIdGenerator>') {
    throw new Error(`Expected exactly one ${anchor} in the donor, found ${count}`)
  }
}

const creator = /Creator="([^"]+)"/.exec(xml)?.[1] ?? 'unknown'

writeFileSync(
  target,
  `// GENERATED by scripts/build-clip-template.mjs — do not edit by hand.
//
// The uncompressed XML of templates/Labyrinth.alc, an empty MIDI clip exported
// from ${creator}. Live is fussy about missing elements, so this is the whole
// donor document rather than a hand-written minimum: the exporter fills in the
// notes and the loop length and changes nothing else.
//
// Imported dynamically so its weight only lands when someone exports.

export const CLIP_TEMPLATE_XML = ${JSON.stringify(xml)}
`,
  'utf8',
)

console.log(
  `wrote ${target}\n  from ${creator}\n  ${xml.length.toLocaleString()} chars of XML`,
)
